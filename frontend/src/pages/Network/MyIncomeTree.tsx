import { useEffect, useMemo, useState } from "react";
import { PublicKey } from "../../evm/address";
import ComponentCard from "../../components/common/ComponentCard";
import PageBreadcrumb from "../../components/common/PageBreadCrumb";
import PageMeta from "../../components/common/PageMeta";
import ContractSlotTree from "../../components/soltrust/ContractSlotTree";
import {
  DEFAULT_REFERRER,
  buildIncomeTree,
  connection,
  formatUserOrdinal,
  getAllPaymentEvents,
  getAllIncomeSlotEntries,
  getAllSolTrustUsers,
  getSolTrustUserAccount,
  groupIncomeBySource,
  maxRecyclesForSlot,
  evmProvider,
  type MatrixTreeNode,
  type SolTrustPaymentEvent,
  type SolTrustIncomeSlotEntry,
  type SolTrustUserAccount,
} from "../../evm/client";
import { INCOME_CATEGORY_STYLES, INCOME_ID_RULES, formatSol, isPersonalIncomeEventType } from "../../evm/plan";

function Metric({ label, value }: { label: string; value: string }) {
  return (
    <div className="rounded-lg bg-gray-50 p-4 dark:bg-white/[0.03]">
      <p className="text-xs font-medium uppercase text-gray-500 dark:text-gray-400">{label}</p>
      <p className="mt-1 text-xl font-semibold text-gray-900 dark:text-white">{value}</p>
    </div>
  );
}
function shortKey(value: string) {
  return value.length <= 13 ? value : `${value.slice(0, 6)}...${value.slice(-6)}`;
}

type LoadState = "idle" | "loading" | "success" | "error";

export default function MyIncomeTree() {
  const rpc = useMemo(() => connection(), []);
  const [wallet, setWallet] = useState("");
  const [lookupWallet, setLookupWallet] = useState(DEFAULT_REFERRER.toBase58());
  const [matrixTree, setMatrixTree] = useState<MatrixTreeNode | null>(null);
  const [paymentEvents, setPaymentEvents] = useState<SolTrustPaymentEvent[]>([]);
  const [allUsers, setAllUsers] = useState<SolTrustUserAccount[]>([]);
  const [incomeEntries, setIncomeEntries] = useState<SolTrustIncomeSlotEntry[]>([]);
  const [selectedSlot, setSelectedSlot] = useState(1);
  const [selectedCycle, setSelectedCycle] = useState(0);
  const [status, setStatus] = useState<LoadState>("idle");
  const [message, setMessage] = useState("");

  useEffect(() => {
    const connected = evmProvider()?.publicKey?.toString();
    if (connected) {
      setWallet(connected);
      setLookupWallet(connected);
      void loadIncomeTree(connected);
    }
  // The initial lookup intentionally runs once with the wallet detected at mount.
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const slotEvents = useMemo(() => {
    const rootWallet = matrixTree?.user.wallet;
    if (!rootWallet) return [];
    // Income-tree ownership follows the final actual beneficiary, independently
    // of the placement/payer that generated the allocation.
    return paymentEvents.filter(
      (event) =>
        event.slotNumber === selectedSlot &&
        event.incomeTreeCycle === selectedCycle &&
        event.incomeTreeOwner === rootWallet,
    );
  }, [matrixTree?.user.wallet, paymentEvents, selectedCycle, selectedSlot]);

  const receivedEvents = useMemo(() => {
    const rootWallet = matrixTree?.user.wallet;
    if (!rootWallet) return [];
    // Recipient-side income is independent from accounting-tree ownership.
    // Example: User 33 can occupy User 5's position while the position rule
    // pays eligible upline User 2. User 2 must see User 33 as the source of
    // the received payment without creating another on-chain entry.
    return paymentEvents.filter(
      (event) =>
        event.slotNumber === selectedSlot && event.cycleKind === 0 &&
        isPersonalIncomeEventType(event.eventType) &&
        event.recipient === rootWallet,
    );
  }, [paymentEvents, matrixTree?.user.wallet, selectedSlot]);

  // The tree shows every income category (direct, matrix, team, upgrade, recycle) so members
  // can see the full picture of what flowed through the matrix, color-coded by category.
  const receiptsBySource = useMemo(() => groupIncomeBySource(receivedEvents, allUsers), [receivedEvents, allUsers]);
  const totalReceived = receivedEvents.reduce((total, event) => total + event.amountSol, 0);
  const incomeSources = receiptsBySource.size;
  const eligibleReceivedEvents = useMemo(() => {
    const rootWallet = matrixTree?.user.wallet;
    if (!rootWallet) return [];
    // Recipient-side source cards span every slot. A user's current income
    // cycle may be Slot 2 while an eligible upline payout was generated by a
    // member operating in Slot 1 (as with User 33 -> User 2).
    return paymentEvents.filter(
      (event) => isPersonalIncomeEventType(event.eventType) && event.recipient === rootWallet,
    );
  }, [paymentEvents, matrixTree?.user.wallet]);
  const usersByWallet = useMemo(
    () => new Map(allUsers.map((user) => [user.wallet, user])),
    [allUsers],
  );
  async function connectWallet() {
    const phantom = evmProvider();
    if (!phantom) {
      setStatus("error");
      setMessage("EVM wallet was not found. Open this site over HTTPS with an EVM wallet installed.");
      return;
    }
    try {
      const response = await phantom.connect();
      const address = response.publicKey.toString();
      setWallet(address);
      setLookupWallet(address);
      setStatus("idle");
      setMessage("");
      await loadIncomeTree(address);
    } catch (error) {
      setStatus("error");
      setMessage(error instanceof Error ? error.message : "Wallet connection failed.");
    }
  }

  async function loadIncomeTree(address = lookupWallet) {
    setStatus("loading");
    setMessage("");
    setMatrixTree(null);
    setPaymentEvents([]);
    setAllUsers([]);
    setIncomeEntries([]);
    setSelectedCycle(0);

    let walletKey: PublicKey;
    try {
      walletKey = new PublicKey(address.trim());
    } catch {
      setStatus("error");
      setMessage("Enter a valid wallet public key.");
      return;
    }

    try {
      const [rootUser, users, events, entries] = await Promise.all([
        getSolTrustUserAccount(rpc, walletKey),
        getAllSolTrustUsers(rpc),
        getAllPaymentEvents(rpc),
        getAllIncomeSlotEntries(rpc),
      ]);
      if (!rootUser) {
        setStatus("error");
        setMessage("This wallet is not registered in the current SolTrust program.");
        return;
      }
      setSelectedCycle(rootUser.incomeTreeCycle);
      setSelectedSlot(1);
      setMatrixTree(buildIncomeTree(
        users,
        events,
        rootUser.wallet,
        rootUser.incomeTreeCycle,
        entries,
        true,
      ));
      setPaymentEvents(events);
      setAllUsers(users);
      setIncomeEntries(entries);
      setStatus("success");
      setMessage("Confirmed cycle credits and three-position slot placements loaded. Legacy per-ID allocations and recycles are not implemented in this contract.");
    } catch (error) {
      setStatus("error");
      setMessage(error instanceof Error ? error.message : "Could not load the income tree.");
    }
  }

  function showIncomeCycle(cycle: number) {
    const owner = matrixTree?.user;
    if (!owner) return;
    const boundedCycle = Math.max(0, Math.min(owner.incomeTreeCycle, cycle));
    const cycleEvents = paymentEvents.filter(
      (event) => event.incomeTreeOwner === owner.wallet && event.incomeTreeCycle === boundedCycle,
    );
    const cycleSlot = cycleEvents[0]?.slotNumber
      ?? (boundedCycle === owner.incomeTreeCycle ? owner.incomeTreeSlot : selectedSlot);
    setSelectedCycle(boundedCycle);
    setSelectedSlot(cycleSlot);
    setMatrixTree(buildIncomeTree(
      allUsers,
      paymentEvents,
      owner.wallet,
      boundedCycle,
      incomeEntries,
      true,
    ));
  }

  return (
    <>
      <PageMeta title="SolTrust Slot Income" description="Confirmed personal USDT received by this wallet, per slot" />
      <div className="solvault-theme">
        <PageBreadcrumb pageTitle="Slot Income" />
        <div className="space-y-6">
          <ComponentCard
            title="Slot Income Lookup"
            desc="Matrix slot placements and confirmed cycle payouts. New live earnings transfer directly to the recipient wallet."
          >
            <div className="grid gap-3 lg:grid-cols-[minmax(0,1fr)_auto_auto]">
              <input
                value={lookupWallet}
                onChange={(event) => setLookupWallet(event.target.value)}
                className="h-11 min-w-0 rounded-lg border border-gray-200 bg-white px-4 text-sm text-gray-800 outline-none focus:border-brand-500 dark:border-gray-800 dark:bg-gray-900 dark:text-white/90"
                placeholder="Registered wallet public key"
              />
              <button
                type="button"
                onClick={() => void loadIncomeTree()}
                disabled={status === "loading"}
                className="h-11 rounded-lg bg-brand-500 px-5 text-sm font-medium text-white hover:bg-brand-600 disabled:opacity-60"
              >
                {status === "loading" ? "Loading" : "Load Slot Income"}
              </button>
              <button
                type="button"
                onClick={connectWallet}
                className="h-11 rounded-lg border border-gray-200 px-5 text-sm font-medium text-gray-700 hover:bg-gray-50 dark:border-gray-800 dark:text-gray-300"
              >
                {wallet ? "Wallet Connected" : "Connect Wallet"}
              </button>
            </div>
            {message && (
              <div className={`rounded-lg border px-4 py-3 text-sm ${status === "error" ? "border-red-200 bg-red-50 text-red-700 dark:border-red-900/50 dark:bg-red-950/30 dark:text-red-300" : "border-emerald-200 bg-emerald-50 text-emerald-700 dark:border-emerald-900/50 dark:bg-emerald-950/30 dark:text-emerald-300"}`}>
                {message}
              </div>
            )}
          </ComponentCard>

          {matrixTree && (
            <>
              <ComponentCard
                title="Income Cycle Navigator"
                desc="Choose an active slot to view placements. Recycling is not implemented in this contract; cycle navigation remains unavailable."
              >
                <div className="flex flex-wrap items-center justify-between gap-3">
                  <select aria-label="Income tree slot" value={selectedSlot} onChange={e=>setSelectedSlot(Number(e.target.value))} className="rounded-lg border border-gray-200 bg-transparent p-2 text-sm dark:border-gray-800 dark:text-white">
                    {Array.from({length:matrixTree.user.currentSlot},(_,i)=><option key={i+1} value={i+1}>Slot {i+1}</option>)}
                  </select>
                  <button
                    type="button"
                    onClick={() => showIncomeCycle(selectedCycle - 1)}
                    disabled={selectedCycle === 0}
                    className="rounded-lg border border-violet-200 px-4 py-2 text-sm font-semibold text-violet-700 hover:bg-violet-50 disabled:cursor-not-allowed disabled:opacity-40 dark:border-violet-900 dark:text-violet-300 dark:hover:bg-violet-950/30"
                  >
                    ← Previous Cycle
                  </button>
                  <div className="text-center">
                    <p className="font-bold text-gray-900 dark:text-white">
                      {selectedCycle === matrixTree.user.incomeTreeCycle ? "Current" : "Previous"} · Cycle {selectedCycle}
                    </p>
                    <p className="text-xs text-gray-500 dark:text-gray-400">
                      Slot {selectedSlot} · Recycle {selectedCycle} of {maxRecyclesForSlot(selectedSlot)}
                    </p>
                  </div>
                  <button
                    type="button"
                    onClick={() => showIncomeCycle(selectedCycle + 1)}
                    disabled={selectedCycle >= matrixTree.user.incomeTreeCycle}
                    className="rounded-lg border border-emerald-200 px-4 py-2 text-sm font-semibold text-emerald-700 hover:bg-emerald-50 disabled:cursor-not-allowed disabled:opacity-40 dark:border-emerald-900 dark:text-emerald-300 dark:hover:bg-emerald-950/30"
                  >
                    Next Cycle →
                  </button>
                </div>
              </ComponentCard>

              <ComponentCard
                title={`Slot ${selectedSlot} Income Tree`}
                desc="Actual three-position slot placements. Live earnings are paid directly to the parent's wallet."
              >
                <div className="w-full overflow-x-auto pb-2">
                  <div className="min-w-full">
                    <ContractSlotTree wallet={matrixTree.user.wallet} slot={selectedSlot} />
                  </div>
                </div>
              </ComponentCard>

              <ComponentCard
                title="Eligible Income Received — Source Users"
                desc="Confirmed cycle payouts aggregate multiple contributions and have no single payer. The contract transfers each live payout directly to the recipient wallet."
              >
                {eligibleReceivedEvents.length ? (
                  <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-3">
                    {[...eligibleReceivedEvents]
                      .sort((left, right) => Number(right.timestamp - left.timestamp))
                      .map((event, index) => {
                        const source = usersByWallet.get(event.payer);
                        const directReferrer = source ? usersByWallet.get(source.referrer) : undefined;
                        const accountingOwner = usersByWallet.get(event.incomeTreeOwner);
                        const creditedEntry = incomeEntries.find((entry) =>
                          entry.owner === matrixTree.user.wallet &&
                          entry.cycle === matrixTree.user.incomeTreeCycle &&
                          entry.member === event.payer,
                        );
                        return (
                          <div key={`${event.matrixId}-${event.idNumber}-${index}`} className="rounded-xl border border-emerald-200 bg-emerald-50/70 p-4 text-sm dark:border-emerald-900/60 dark:bg-emerald-950/20">
                            <p className="text-xs font-bold uppercase tracking-wide text-emerald-700 dark:text-emerald-300">Income received</p>
                            <p className="mt-1 text-lg font-bold text-gray-900 dark:text-white">
                              {event.cycleKind===2?"Global Pool":"Matrix"} cycle credit
                            </p>
                            <div className="mt-3 space-y-1 text-xs text-gray-600 dark:text-gray-300">
                              <p><span className="font-semibold">Generated by:</span> {source ? formatUserOrdinal(source.userId) : "Multiple cycle contributions"}</p>
                              <p><span className="font-semibold">Direct referrer:</span> {directReferrer ? formatUserOrdinal(directReferrer.userId) : source ? shortKey(source.referrer) : "Unknown"}</p>
                              <p><span className="font-semibold">Accounting tree:</span> {accountingOwner ? formatUserOrdinal(accountingOwner.userId) : shortKey(event.incomeTreeOwner)}</p>
                              <p><span className="font-semibold">Accounting position:</span> {event.incomeTreePosition}</p>
                              <p><span className="font-semibold">Source slot:</span> {event.slotNumber}</p>
                              <p><span className="font-semibold">Received by:</span> {formatUserOrdinal(matrixTree.user.userId)}</p>
                              <p><span className="font-semibold">Recipient income position:</span> {creditedEntry?.position ?? "Pending on-chain credit"}</p>
                              <p><span className="font-semibold">Source payment ID:</span> {event.idNumber}</p>
                            </div>
                            <p className="mt-3 text-base font-bold text-emerald-700 dark:text-emerald-300">{formatSol(event.amountSol)}</p>
                            <p className="mt-1 text-[10px] text-gray-500 dark:text-gray-400">One payment transfer with an independently recorded recipient-tree position.</p>
                          </div>
                        );
                      })}
                  </div>
                ) : (
                  <p className="py-6 text-center text-sm text-gray-500 dark:text-gray-400">No eligible income has been received by this wallet.</p>
                )}
              </ComponentCard>

              <ComponentCard title="My Personal Income — Received in Wallet">
                <div className="mb-5 grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
                  <Metric label="Root user" value={formatUserOrdinal(matrixTree.user.userId)} />
                  <Metric label="Selected slot" value={String(selectedSlot)} />
                  <Metric label="Income sources" value={String(incomeSources)} />
                  <Metric label="Total received" value={formatSol(totalReceived)} />
                </div>
                <div className="mb-6 flex flex-wrap gap-2">
                  {Array.from({ length: 12 }, (_, index) => index + 1).map((slot) => (
                    <button
                      type="button"
                      key={slot}
                      onClick={() => setSelectedSlot(slot)}
                      className={`rounded-lg border px-3 py-2 text-sm font-semibold ${selectedSlot === slot ? "border-brand-500 bg-brand-500 text-white" : "border-gray-200 bg-white text-gray-700 dark:border-gray-800 dark:bg-gray-900 dark:text-gray-300"}`}
                    >
                      Slot {slot}
                    </button>
                  ))}
                </div>
                <div className="rounded-xl border border-blue-200 bg-blue-50 p-4 text-sm text-blue-800 dark:border-blue-900/60 dark:bg-blue-950/20 dark:text-blue-300">
                  <strong>Legacy per-ID view unavailable:</strong> The original position-specific allocations below are not implemented by this EVM contract. Actual slot placements appear above. Cycle credits aggregate three contributions; there is no single payer or per-ID payout.
                </div>
                <div className="mt-6 space-y-6">
                  {([1, 2, 3] as const).map((level) => (
                    <div key={level}>
                      <div className="mb-3 flex items-center gap-3">
                        <span className="rounded-full bg-brand-500 px-3 py-1 text-xs font-bold text-white">Level {level}</span>
                        <span className="text-xs text-gray-500 dark:text-gray-400">
                          Personal-income positions {INCOME_ID_RULES.filter((rule) => rule.level === level && (rule.normalRecipient === "wallet" || rule.normalRecipient === "upline")).map((rule) => rule.position).join(", ")}
                        </span>
                      </div>
                      <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-4 xl:grid-cols-7">
                        {INCOME_ID_RULES.filter((rule) => rule.level === level && (rule.normalRecipient === "wallet" || rule.normalRecipient === "upline")).map((rule) => {
                          const events = receivedEvents.filter((event) => event.idNumber === rule.id);
                          const amount = events.reduce((sum, event) => sum + event.amountSol, 0);
                          const category = INCOME_CATEGORY_STYLES[rule.normalRecipient];
                          return (
                            <div key={rule.id} className={`rounded-xl border p-4 ${events.length ? `border-transparent ${category.badge}` : "border-gray-200 bg-white dark:border-gray-800 dark:bg-gray-900"}`}>
                              <div className="flex items-center gap-1.5">
                                <span className={`h-2 w-2 shrink-0 rounded-full ${category.dot}`} />
                                <p className="text-xs font-semibold uppercase text-gray-500 dark:text-gray-400">Position {rule.position} · {category.label}</p>
                              </div>
                              <p className="mt-1 text-sm font-bold text-gray-900 dark:text-white">{rule.label}</p>
                              <p className="mt-2 text-xs font-semibold">
                                {events.length ? `${formatSol(amount)} credited` : <span className="text-gray-500">Not implemented</span>}
                              </p>
                              {events.length > 0 && <p className="mt-1 font-mono text-[10px] opacity-70">From {shortKey(events[0].payer)}</p>}
                            </div>
                          );
                        })}
                      </div>
                    </div>
                  ))}
                </div>
                <div className="mt-6 rounded-xl border border-gray-200 bg-gray-50/60 p-4 dark:border-gray-800 dark:bg-white/[0.02]">
                  <p className="font-semibold text-gray-700 dark:text-gray-200">Not included in My Income — still shown in your tree above</p>
                  <div className="mt-3 grid gap-3 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-6">
                    {INCOME_ID_RULES.filter((rule) => rule.normalRecipient !== "wallet" && rule.normalRecipient !== "upline").map((rule) => {
                      const events = slotEvents.filter((event) => event.idNumber === rule.id);
                      const amount = events.reduce((sum, event) => sum + event.amountSol, 0);
                      const category = INCOME_CATEGORY_STYLES[rule.normalRecipient];
                      return (
                        <div key={rule.id} className={`rounded-lg border p-3 ${events.length ? `border-transparent ${category.badge}` : "border-gray-200 bg-white dark:border-gray-800 dark:bg-gray-900"}`}>
                          <div className="flex items-center gap-1.5">
                            <span className={`h-2 w-2 shrink-0 rounded-full ${category.dot}`} />
                            <p className="text-xs font-semibold uppercase text-gray-500 dark:text-gray-400">Position {rule.position} · {category.label}</p>
                          </div>
                          <p className="mt-1 text-sm font-bold text-gray-900 dark:text-white">{rule.label}</p>
                          <p className="mt-1 text-xs opacity-80">
                            {events.length ? `${formatSol(amount)} allocated — excluded from personal earnings` : "Excluded from personal earnings"}
                          </p>
                        </div>
                      );
                    })}
                  </div>
                </div>
                {receivedEvents.length === 0 && <p className="mt-6 text-center text-sm text-gray-500 dark:text-gray-400">No confirmed personal income has been received in Slot {selectedSlot}.</p>}
              </ComponentCard>
            </>
          )}
        </div>
      </div>
    </>
  );
}
